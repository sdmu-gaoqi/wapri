/**
 * 正则集中维护
 *
 * 约定：
 * 1. 这里只导出「创建正则」的函数，不直接导出正则对象。
 * 2. 正则用字符串 + new RegExp 构造，而不是正则字面量。
 *    字面量会在脚本解析阶段就被引擎校验，一旦用到浏览器不支持的语法（如 lookbehind），
 *    解析期就会抛 SyntaxError，导致整个模块加载失败，调用方的 try/catch 也拦不住；
 *    字符串形式把编译推迟到调用时，异常才能被捕获并降级。
 * 3. 校验方法（src/regexp.ts）只负责调用，不内联正则。
 */

/** 邮箱 */
export const regexpEmail = () => new RegExp('^[\\w.%+-]+@(?:[\\w-]+\\.)+[a-zA-Z]{2,}$')

/** 手机号（中国大陆 11 位，1 开头，第二位 3-9） */
export const regexpPhone = () => new RegExp('^1[3-9]\\d{9}$')
